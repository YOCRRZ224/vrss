def remove_generated_tags(content):
    """
    Remove previously generated OG/Twitter tags.

    This makes the generator idempotent.
    """

    pattern = re.compile(
        r"\s*<meta\s+"
        r"(?:property|name)\s*=\s*"
        r"""(["'])(?:og:title|og:description|og:type|og:url|og:image|"""
        r"""og:image:width|og:image:height|og:site_name|"""
        r"""article:published_time|twitter:card|twitter:title|"""
        r"""twitter:description|twitter:image)\1"""
        r"""[^>]*>\s*""",
        re.IGNORECASE,
    )

    return pattern.sub(
        "\n",
        content,
    )


def inject_metadata(
    content,
    title,
    description,
    timestamp,
    post_url,
    image_url,
):
    """
    Inject OG and Twitter metadata into <head>.
    """

    content = remove_generated_tags(content)

    escaped_title = html.escape(
        title,
        quote=True,
    )

    escaped_description = html.escape(
        description,
        quote=True,
    )

    escaped_timestamp = html.escape(
        timestamp,
        quote=True,
    )

    escaped_url = html.escape(
        post_url,
        quote=True,
    )

    escaped_image = html.escape(
        image_url,
        quote=True,
    )

    tags = f"""
    <meta property="og:title" content="{escaped_title}">
    <meta property="og:description" content="{escaped_description}">
    <meta property="og:type" content="article">
    <meta property="og:url" content="{escaped_url}">
    <meta property="og:image" content="{escaped_image}">
    <meta property="og:image:width" content="1200">
    <meta property="og:image:height" content="630">
    <meta property="og:site_name" content="VORCINEX_STUDIO vRSS">
    <meta property="article:published_time" content="{escaped_timestamp}">

    <meta name="twitter:card" content="summary_large_image">
    <meta name="twitter:title" content="{escaped_title}">
    <meta name="twitter:description" content="{escaped_description}">
    <meta name="twitter:image" content="{escaped_image}">
"""

    head_match = re.search(
        r"</head>",
        content,
        re.IGNORECASE,
    )

    if not head_match:
        raise RuntimeError(
            "Could not find </head> in blog HTML."
        )

    position = head_match.start()

    return (
        content[:position]
        + tags
        + "\n"
        + content[position:]
    )


def process_blog(path):
    """
    Process one blog post.
    """

    original = path.read_text(
        encoding="utf-8",
    )

    parser = MetadataParser()

    parser.feed(original)

    title = clean_text(
        parser.title
    )

    description = clean_text(
        parser.description
    )

    timestamp = parser.timestamp.strip()

    author = clean_text(
        parser.author
    )

    # If the server description is missing or unusable,
    # generate one from the article body.
    if not description:
        body_parser = BodyTextParser()
        body_parser.feed(original)

        description = truncate_text(
            " ".join(body_parser.text),
            160,
        )

    else:
        description = truncate_text(
            description,
            160,
        )

    if not title:
        print(
            f"Skipping {path}: missing blog-title."
        )
        return False

    if not timestamp:
        print(
            f"Skipping {path}: missing blog-timestamp."
        )
        return False

    post_url = format_url(path)

    image_name = f"{path.stem}.png"

    image_path = OG_DIR / image_name

    image_url = (
        f"{SITE_URL}/assets/og/{image_name}"
    )

    generate_image(
        title=title,
        description=description,
        timestamp=timestamp,
        author=author,
        output=image_path,
    )

    updated = inject_metadata(
        content=original,
        title=title,
        description=description,
        timestamp=timestamp,
        post_url=post_url,
        image_url=image_url,
    )

    if updated != original:
        path.write_text(
            updated,
            encoding="utf-8",
        )

        changed = "updated"

    else:
        changed = "unchanged"

    print(
        f"{changed}: {path} → {image_path}"
    )

    return True


def main():
    BLOG_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    OG_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    posts = sorted(
        BLOG_DIR.glob("*.html")
    )

    if not posts:
        print(
            "No blog posts found."
        )
        return

    processed = 0

    for path in posts:
        if process_blog(path):
            processed += 1

    print()
    print(
        f"Processed {processed}/{len(posts)} blog posts."
    )


if __name__ == "__main__":
    main()
