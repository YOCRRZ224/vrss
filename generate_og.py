def wrap_text(draw, text, font, max_width):
    """
    Word-wrap text so it fits within max_width.
    """

    words = text.split()

    lines = []
    current = ""

    for word in words:
        candidate = (
            word
            if not current
            else f"{current} {word}"
        )

        bbox = draw.textbbox(
            (0, 0),
            candidate,
            font=font,
        )

        width = bbox[2] - bbox[0]

        if width <= max_width:
            current = candidate
        else:
            if current:
                lines.append(current)

            current = word

    if current:
        lines.append(current)

    return lines


def draw_title(draw, title, font):
    """
    Draw a large editorial title.
    """

    max_width = 1020

    lines = wrap_text(
        draw,
        title,
        font,
        max_width,
    )

    # Keep the image from becoming overcrowded.
    if len(lines) > 3:
        lines = lines[:3]

        last = lines[-1]

        if len(last) > 3:
            lines[-1] = last.rstrip(" .,-") + "…"

    x = 90
    y = 190

    line_spacing = 8

    for line in lines:
        draw.text(
            (x, y),
            line,
            font=font,
            fill=INK,
        )

        bbox = draw.textbbox(
            (x, y),
            line,
            font=font,
        )

        height = bbox[3] - bbox[1]

        y += height + line_spacing

    return y


def generate_image(
    title,
    description,
    timestamp,
    author,
    output,
):
    """
    Generate the 1200x630 OG image.
    """

    image = Image.new(
        "RGB",
        (WIDTH, HEIGHT),
        PAPER,
    )

    draw = ImageDraw.Draw(image)

    fonts = get_fonts()

    # Outer border
    draw.rectangle(
        (
            24,
            24,
            WIDTH - 25,
            HEIGHT - 25,
        ),
        outline=BORDER,
        width=2,
    )

    # Accent mark
    draw.ellipse(
        (
            82,
            76,
            96,
            90,
        ),
        fill=ACCENT,
    )

    # Brand
    draw.text(
        (115, 70),
        "VORCINEX_STUDIO",
        font=fonts["mono"],
        fill=INK,
    )

    # vRSS label
    draw.text(
        (90, 130),
        "DAILY BLOG",
        font=fonts["mono_small"],
        fill=MUTED,
    )

    # Title
    draw_title(
        draw,
        title,
        fonts["title"],
    )

    # Metadata
    date = format_date(timestamp)

    metadata = []

    if author:
        metadata.append(author)

    if date:
        metadata.append(date)

    metadata_text = " · ".join(metadata)

    if metadata_text:
        draw.text(
            (90, 490),
            metadata_text,
            font=fonts["mono_small"],
            fill=MUTED,
        )

    # Bottom domain
    draw.text(
        (90, 555),
        "blog.vorcinex.yocrrz.is-a.dev",
        font=fonts["mono_small"],
        fill=FAINT,
    )

    # Small accent line
    draw.line(
        (
            WIDTH - 260,
            560,
            WIDTH - 90,
            560,
        ),
        fill=ACCENT,
        width=2,
    )

    output.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    image.save(
        output,
        format="PNG",
        optimize=True,
    )


