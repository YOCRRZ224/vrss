#!/usr/bin/env python3

"""
Generate Open Graph images and social metadata for vRSS blog posts.

Input:
    blog/*.html

Output:
    assets/og/<post>.png
    Updated blog/*.html with OG + Twitter metadata
"""

from html import unescape
from html.parser import HTMLParser
from pathlib import Path
from datetime import datetime, timezone
import html
import os
import re

from PIL import Image, ImageDraw, ImageFont


SITE_URL = os.getenv(
    "VRSS_SITE_URL",
    "https://blog.vorcinex.yocrrz.is-a.dev",
).rstrip("/")


BLOG_DIR = Path("blog")
OG_DIR = Path("assets/og")


WIDTH = 1200
HEIGHT = 630


# vRSS palette
PAPER = "#f7f3e8"
PAPER_DEEP = "#eee8d8"
SURFACE = "#fbf9f3"

INK = "#252321"
INK_SOFT = "#4f4a43"
MUTED = "#817b70"
FAINT = "#aaa397"

BORDER = "#ded8c9"
ACCENT = "#c45a3d"


class MetadataParser(HTMLParser):
    """
    Extract the metadata already generated by the vRSS server.
    """

    def __init__(self):
        super().__init__()

        self.title = ""
        self.description = ""
        self.timestamp = ""
        self.author = ""

        self._in_author = False
        self._author_text = []

    def handle_starttag(self, tag, attrs):
        tag = tag.lower()
        attrs = dict(attrs)

        if tag == "meta":
            name = attrs.get("name", "").lower()
            content = attrs.get("content", "")

            if name == "blog-title":
                self.title = unescape(content)

            elif name == "description":
                self.description = unescape(content)

            elif name == "blog-timestamp":
                self.timestamp = unescape(content)

        elif tag == "div":
            classes = attrs.get("class", "").split()

            if "author" in classes:
                self._in_author = True

    def handle_endtag(self, tag):
        if tag.lower() == "div" and self._in_author:
            self._in_author = False

            text = " ".join(self._author_text)
            text = re.sub(r"\s+", " ", text).strip()

            match = re.search(
                r"Published\s+by\s+(.+)$",
                text,
                re.IGNORECASE,
            )

            if match:
                self.author = match.group(1).strip()

            self._author_text = []

    def handle_data(self, data):
        if self._in_author:
            self._author_text.append(data)


class BodyTextParser(HTMLParser):
    """
    Extract readable text from the article body.
    """

    def __init__(self):
        super().__init__()

        self.text = []

        self._skip = 0

    def handle_starttag(self, tag, attrs):
        tag = tag.lower()

        if tag in {
            "script",
            "style",
            "svg",
            "noscript",
            "iframe",
        }:
            self._skip += 1

    def handle_endtag(self, tag):
        tag = tag.lower()

        if tag in {
            "script",
            "style",
            "svg",
            "noscript",
            "iframe",
        }:
            self._skip = max(0, self._skip - 1)

    def handle_data(self, data):
        if self._skip:
            return

        data = data.strip()

        if data:
            self.text.append(data)


def clean_text(value):
    """
    Convert HTML-ish text into readable plain text.
    """

    value = unescape(value)

    value = re.sub(
        r"<[^>]+>",
        " ",
        value,
    )

    value = re.sub(
        r"\s+",
        " ",
        value,
    )

    return value.strip()


def truncate_text(value, length=160):
    value = clean_text(value)

    if len(value) <= length:
        return value

    return value[: length - 1].rstrip() + "…"


def parse_timestamp(timestamp):
    """
    Convert an ISO timestamp into UTC.
    """

    if not timestamp:
        return None

    try:
        dt = datetime.fromisoformat(timestamp)

    except ValueError:
        return None

    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)

    return dt.astimezone(timezone.utc)


def format_date(timestamp):
    dt = parse_timestamp(timestamp)

    if not dt:
        return ""

    return dt.strftime("%d %b %Y")


def format_url(path):
    """
    Convert blog/<file>.html into the public URL.
    """

    relative = path.as_posix().lstrip("/")

    return f"{SITE_URL}/{relative}"


def get_font(paths, size):
    """
    Load the first available font from the supplied paths.
    """

    for path in paths:
        path = Path(path)

        if path.exists():
            return ImageFont.truetype(
                str(path),
                size,
            )

    return ImageFont.load_default()


